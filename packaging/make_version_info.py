"""Write packaging/version_info.txt (Windows file properties) from aethernode.__version__.

Gives AetherNode.exe a consistent Product name / version in Explorer's Properties ->
Details tab, which code signing (SignPath metadata restrictions) checks.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from aethernode import __version__  # noqa: E402

parts = [int(p) for p in __version__.split(".")[:3]]
nums = tuple(parts + [0] * (4 - len(parts)))

TEMPLATE = f"""# UTF-8 -- generated by packaging/make_version_info.py, do not edit
VSVersionInfo(
  ffi=FixedFileInfo(filevers={nums}, prodvers={nums}, mask=0x3f, flags=0x0, OS=0x40004,
                    fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([StringTable('040904B0', [
      StringStruct('CompanyName', 'AetherNode contributors'),
      StringStruct('FileDescription', 'AetherNode - home network device monitor'),
      StringStruct('FileVersion', '{__version__}'),
      StringStruct('InternalName', 'AetherNode'),
      StringStruct('LegalCopyright', 'Copyright (c) 2026 AetherNode contributors. MIT License.'),
      StringStruct('OriginalFilename', 'AetherNode.exe'),
      StringStruct('ProductName', 'AetherNode'),
      StringStruct('ProductVersion', '{__version__}')])]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""

out = Path(__file__).with_name("version_info.txt")
out.write_text(TEMPLATE, encoding="utf-8")
print("wrote", out, "for version", __version__)
